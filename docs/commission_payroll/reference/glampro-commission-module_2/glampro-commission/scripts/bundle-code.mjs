// Writes docs/ALL_CODE.md – the whole codebase in one Markdown file, ready to upload to ChatGPT.
// Run: node scripts/bundle-code.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const include = ['AI_HANDOFF.md', 'README.md', 'package.json', 'tsconfig.base.json', 'shared', 'backend', 'frontend'];
const skip = new Set(['node_modules', 'dist', '.env']);
const exts = new Set(['.ts', '.tsx', '.css', '.json', '.prisma', '.sql', '.html', '.md', '.example']);
const lang = { '.ts': 'ts', '.tsx': 'tsx', '.css': 'css', '.json': 'json', '.prisma': 'prisma', '.sql': 'sql', '.html': 'html', '.md': 'md' };
const files = [];
const walk = (p) => {
  const st = fs.statSync(p);
  if (st.isDirectory()) { for (const f of fs.readdirSync(p).sort()) if (!skip.has(f) && f !== 'package-lock.json') walk(path.join(p, f)); }
  else if (exts.has(path.extname(p)) || p.endsWith('.env.example')) files.push(p);
};
include.forEach((i) => walk(path.join(root, i)));
let out = '# Glampro Commission Module – full source\n\nGenerated by scripts/bundle-code.mjs. Read AI_HANDOFF.md (first file) before changing code.\n\n## Files\n\n';
out += files.map((f) => `- ${path.relative(root, f)}`).join('\n') + '\n\n';
for (const f of files) {
  const rel = path.relative(root, f);
  const fence = rel.endsWith('.md') ? '````' : '```';
  out += `## ${rel}\n\n${fence}${lang[path.extname(f)] ?? ''}\n${fs.readFileSync(f, 'utf8').trimEnd()}\n${fence}\n\n`;
}
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'ALL_CODE.md'), out);
console.log(`docs/ALL_CODE.md written: ${files.length} files, ${(out.length / 1024).toFixed(0)} KB`);
